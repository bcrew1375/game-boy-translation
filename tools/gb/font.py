ENGLISH_TILE_CHARACTERS = {
    0x00: " ",
    **{index + 0x01: chr(ord("A") + index) for index in range(26)},
    **{index + 0x1B: chr(ord("a") + index) for index in range(26)},
    **{
        0x35 + index: character
        for index, character in enumerate(".,'\"?!:;-/()[]&+=%*#")
    },
    **{0x80 + index: str(index) for index in range(10)},
    0x96: "H",
    0x97: "P",
    0x98: "K",
    0x99: "I",
    0x9A: "S",
    0x9B: "A",
    0x9C: "B",
    0x9D: "D",
    0x9E: "←",
    0x9F: "→",
}


def glyph_bytes(character: str) -> bytes:
    """Render one repository-defined five-by-seven glyph as packed 1bpp rows."""
    rows = GLYPH_ROWS[character]
    return bytes(int(row, 2) << 2 for row in rows) + b"\x00"


def build_english_font(original_font: bytes) -> bytes:
    """Build 160 glyphs, preserving original numeric/UI tiles $80-$9F."""
    if len(original_font) != FONT_DECOMPRESSED_SIZE:
        raise FontCodecError(
            f"original font must be {FONT_DECOMPRESSED_SIZE} bytes, got {len(original_font)}"
        )
    result = bytearray(FONT_DECOMPRESSED_SIZE)
    for tile_id, character in ENGLISH_TILE_CHARACTERS.items():
        if tile_id >= 0x80:
            continue
        if character != " ":
            result[tile_id * 8 : tile_id * 8 + 8] = glyph_bytes(character)
    result[0x80 * 8 : 0xA0 * 8] = original_font[0x80 * 8 : 0xA0 * 8]
    return bytes(result)